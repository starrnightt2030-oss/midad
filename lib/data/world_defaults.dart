String _norm(String s) =>
    s.replaceAll(RegExp(r'[\s\.\-ـ«»]'), '').replaceAll(RegExp('[أإآ]'), 'ا').replaceAll('ة', 'ه').replaceAll('ى', 'ي');

/// القسم الأساسي بالمعرّف، أو بالاسم لو المعرّف مختلف.
WorldDefault? worldDefaultFor(String id, String name) {
  for (final d in worldDefaults) {
    if (d.id == id) return d;
  }
  final n = _norm(name);
  if (n.isEmpty) return null;
  for (final d in worldDefaults) {
    if (_norm(d.name) == n) return d;
  }
  return null;
}
